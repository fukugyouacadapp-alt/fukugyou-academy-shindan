import type { CONTRACT_STYLES, MARKET_NEEDS } from '@/lib/schemas'

/**
 * 診断結果の部品（あらかじめ用意した文面）の形。
 * 結果は AI を使わず、ここに書いた部品を回答に合わせて選び・組み立てて作る（src/lib/diagnose.ts）。
 * 部品を足す・直したら `npm run check:results` で決まりごとを点検する。
 *
 * ── 書き方の決まり（docs/02-result-rules.md にも同じことを書いている） ──
 * - 中学生にもわかる言葉で書く。横文字は必要なものだけ。「〜が向いています」「〜で活きます」と前向きに
 * - 「副業」ではなく「複業」と書く（2026-10-26 にそろえた）。keywords だけは、募集サイトで実際に引く検索語なので「副業」のままでよい
 * - お金：金額（月○万円・時給○円など）、「稼げる」「儲かる」「確実に」「誰でも」「高収入」「楽して」は書かない
 * - 資格や許可が必要な仕事は入れない：税務書類の作成・税務相談、官公署に出す書類や補助金申請書の作成代行、
 *   社会保険の手続き代行、登記、法律相談・契約書の作成代行やリーガルチェック、医療・診断・治療にあたる行為、
 *   投資の助言・銘柄のおすすめ・金融商品の勧誘、保険の募集、有料の人材紹介・転職のあっせん、
 *   不動産の売買・賃貸の仲介、旅行の手配・販売、健康食品やサプリ・体づくりで効き目をうたうこと。
 *   関わる強みを活かすときは「資格者のサポート（資料集め・情報整理・事務）」や「制度をわかりやすく伝える発信・講師」の形にする
 * - 初期費用や高額講座が前提のもの、情報商材、ネットワークビジネス、アフィリエイトだけのもの、
 *   本業の会社の顧客や社外秘の情報を使うものも入れない
 * - 「医療行為はしない」のような断り書きも、本文（what など）ではなく caution に書く（本文の点検に引っかかるため）
 * - 海外で広がっている働き方も入れてよい。そのときは what に「海外では『〇〇』と呼ばれ、広がっている働き方です。」のように一言添える
 * - 日本にいながら海外の会社・人から受ける仕事も入れてよい。海外の会社が日本にいる人を実際に募集しているものだけにする。英語の設問は無いので、日本語の力や日本の現場の知識が売りになるものにする。やりとりに英語が要りそうなら caution に書く
 */

export type ContractStyle = (typeof CONTRACT_STYLES)[number]
export type MarketNeed = (typeof MARKET_NEEDS)[number]

/** 回答の選択肢ID（src/data/questions.ts）。q2〜q6 のものだけ使う（「特にない」系は使わない） */
export type AnswerId = string

/** おすすめの仕事1件 */
export type Job = {
  /** 部品の名前。ファイルの中で重ならなければよい（例: 'hr-1'） */
  id: string
  /** 職種名。「対象＋仕事内容」の形で25字以内。読んだ人が1秒で何をする仕事かわかる言葉（例: '保育園・介護施設向け 求人票の書き直し'） */
  title: string
  /**
   * 掛け合わせた強みのタグ（# から始める・2〜3個・1つ12字以内）。自己紹介や案件検索にそのまま使える、仕事として通じる言葉。
   * 顕在型：1つ目に本業スキル側のタグ。潜在型：1つ目に「仕事の外の経験」側のタグ（結果の「潜在型」の層にはこれが入る）
   */
  tags: string[]
  /** どんな仕事か（1〜2文・90字以内・「。」で終える） */
  what: string
  /** 困っている人・会社（具体的に・60字以内・名詞で終える。「。」は付けない） */
  who: string
  /**
   * 向いている理由の後半（1文・70字以内・「〜ます。」で終える）。
   * 画面では、その人が選んだ回答の引用2つのあとに「〜ので、」でつながる
   * （例: 人事では「求人票・採用広報」を担当してきたうえに、人から「資料や文章を整える」と頼まれることが多いので、＋ because）。
   * 前に「〜ので、」が付くので、中に「ので」「から」を入れない（「〜を知っているので、〜できます。」は✗）。
   * どの回答が引用されるかは人によって変わるので、特定の回答を言い直さず、この仕事で何ができるかを書く。
   * 潜在型は「仕事の外の経験」（例: 「SNSやブログでの発信」を続けてきた）が必ず先に引用されるので、その経験も言い直さない
   */
  because: string
  /** ライバルが少ない理由（1文・80字以内・「〜からです。」で終える） */
  niche: string
  contract: ContractStyle
  /** 複業・業務委託の場（クラウドワークス・ランサーズ・ココナラ・Workship など）で案件が見つかる見込み。自信がないものを◎にしない */
  market: MarketNeed
  /** 複業サイトで案件を探すときの検索語（2〜3個・1つ20字以内。募集サイトでは「副業」で引くことが多いので、ここだけ「副業」と書いてよい）。結果画面の「案件を探すキーワード」の欄を外したので、いまは画面に出していない（戻すときのために残す） */
  keywords: string[]
  /** 今週できる最初の一歩（30分〜2時間でできること・1文・70字以内・「。」で終える） */
  step: string
  /** 前に出る（講師・面談・相談・営業）か、裏方（制作・代行・仕組みづくり）か */
  stage: 'front' | 'back'
  /** 相手は会社（toB）か、個人（toC）か */
  target: 'b' | 'c'
  /** 毎週の定例や、継続的な関わりがないと成り立たない仕事（使える時間が週3時間未満の人には上位に出さない） */
  regular?: true
  /** 地域の中小企業・NPO・学校・地域の団体などの役に立つ仕事（「社会や地域の役に立ちたい」人に上位で出す） */
  social?: true
  /**
   * この仕事の根拠になる回答の選択肢ID（上ほど強い・2〜5個）。q2〜q6 の ID（例: 'q3.2'）。
   * 選ばれていると順位が上がり、「向いている理由」で引用され、強み活用度が◎になる（q2・q3 のとき）
   */
  evidence: AnswerId[]
  /** 顕在型だけ：STEP5（深掘り）のどの答えに合う仕事か（1〜4。questions.ts の deep.options の番号） */
  deep?: number[]
  /** 潜在型だけ：仕事の内容（1〜4。family の details の番号）のうち、とくに合うもの。合う人に少し上位で出す（それ以外の人にも出ることはある） */
  details?: number[]
  /** この仕事を選んだ人に出す注意点（1文・100字以内）。必要なときだけ */
  caution?: string
}

/** 仕事の内容（1-2「具体的には？」の選択肢）1つぶんの部品 */
export type Detail = {
  /** questions.ts の JOB_FAMILIES の details[].label と同じ文言 */
  label: string
  /** 二つ名の後ろ半分（10字以内の名詞）。前に「本音を引き出す」「ITに強い」などが付く（例: '採用の伴走者'） */
  role: string
  /** 本業の層のタグ（2〜3個） */
  tags: string[]
  /** ナレッジ（20字以内。例: '採用の一連の流れ'）。強みの3要素の欄を外したので、いまは画面に出していない（戻すときのために残す） */
  know: string
  /**
   * 得意な市場の名前の前半（20字以内の名詞）。後ろに「を裏方で支える仕事」「を前に立って支える仕事」が付く。
   * b は会社を相手にする人向け、c は個人を相手にする人向け（例: { b: '会社の採用・人づくり', c: '働く人のキャリア' }）
   */
  field: { b: string; c: string }
  /** 会社と個人のどちらとも決めていない人に、どちらの field を使うか */
  lean: 'b' | 'c'
  /** 伸ばすと選択肢が広がる強み（1文・80字以内） */
  growth: string
  /** この仕事の内容の人に出す注意点（公務員の複業の許可など）。必要なときだけ */
  caution?: string
  /** STEP5（深掘り）の4つの答えそれぞれの、本業のタグと、ナレッジ（20字以内。know はいまは画面に出していない）。questions.ts の deep.options と同じ順 */
  deep: { tag: string; know: string }[]
  /** 顕在型（本業スキルを、別の会社・別の立場で活かす仕事）。2026-11-11 に案件の少ない仕事（△）を外したので、1〜5つ（足りない分は diagnose.ts が同じタイプのほかの仕事の内容から補う）。regular は2つまで */
  jobs: Job[]
}

/** 仕事のタイプ（1 の選択肢）1つぶんの部品 */
export type Family = {
  /** questions.ts の JOB_FAMILIES の label と同じ文言 */
  label: string
  /** 仕事の内容4つ。questions.ts と同じ順 */
  details: Detail[]
  /**
   * 潜在型（仕事の外の経験 × 本業スキル）。「仕事の外で、人に話せる経験」の選択肢ごとに0〜3つ（2026-11-11 に△を外したので、0のものもある。そのときは extension から出す）。
   * キーは選択肢ID（q6.1 子育て・介護と仕事の両立／q6.2 地域活動・PTA・ボランティア／q6.3 SNSやブログでの発信／
   * q6.4 趣味・スポーツ・ものづくり／q6.5 転職や病気など、大きな壁を越えた経験）。
   * 3つのうち2つ以上は、このタイプのどの仕事の内容の人が読んでも不自然でないものにする
   */
  hidden: Record<'q6.1' | 'q6.2' | 'q6.3' | 'q6.4' | 'q6.5', Job[]>
  /** 潜在型（本業の延長）。仕事の外の経験が「特にない」人に出す。頼まれること・やる気が出る瞬間を根拠にする。1〜3つ */
  extension: Job[]
}
